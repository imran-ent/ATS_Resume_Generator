/* ─── Personal ───────────────────────────────────────────────────────── */

export function PersonalSection() {
  const { data, patch } = useResumeDraft()
  if (!data) return null
  const p = data.personal
  const set = (patchPart: Partial<typeof p>) => patch({ personal: { ...p, ...patchPart } })
  const setContact = (patchPart: Partial<typeof p.contact>) =>
    patch({ personal: { ...p, contact: { ...p.contact, ...patchPart } } })

  return (
    <EditorSection
      title="Personal Information"
      icon={<User className="size-4" />}
      badge={p.fullName ? 'Complete' : 'Incomplete'}
    >
      <div className="grid gap-4 sm:grid-cols-2">
        <TextField label="Full Name" value={p.fullName} onChange={(e) => set({ fullName: e.target.value })} />
        <TextField label="Professional Title" value={p.professionalTitle} onChange={(e) => set({ professionalTitle: e.target.value })} />
        <TextField label="Email" type="email" value={p.contact.email} onChange={(e) => setContact({ email: e.target.value })} />
        <TextField label="Phone" value={p.contact.phone} onChange={(e) => setContact({ phone: e.target.value })} />
        <TextField label="Location" value={p.contact.location} onChange={(e) => setContact({ location: e.target.value })} />
        <TextField label="LinkedIn" value={p.contact.linkedin} onChange={(e) => setContact({ linkedin: e.target.value })} />
        <TextField label="GitHub" value={p.contact.github} onChange={(e) => setContact({ github: e.target.value })} />
        <TextField label="Portfolio" value={p.contact.portfolio} onChange={(e) => setContact({ portfolio: e.target.value })} />
      </div>
      <div className="mt-4 flex items-center gap-3">
        <Switch
          checked={data.settings.includePhoto}
          onCheckedChange={(v) => patch({ settings: { ...data.settings, includePhoto: v } })}
          label="Include photo"
        />
        <span className="text-sm text-muted">Include photo on resume</span>
      </div>
    </EditorSection>
  )
}

/* ─── Summary ────────────────────────────────────────────────────────── */

export function SummarySection() {
  const { data, patch } = useResumeDraft()
  const toast = useUiStore((s) => s.toast)
  const [loading, setLoading] = useState(false)
  if (!data) return null

  const generate = async () => {
    setLoading(true)
    try {
      const res = await aiProvider.generate({
        resume: data,
        action: 'generate-summary',
        jobDescription: data.targetJob.jobDescription,
      })
      if (res.summary) {
        patch({ summary: res.summary, summarySource: 'ai' })
        toast({ title: 'Summary generated', variant: 'success' })
      }
    } catch (err) {
      toast({
        title: 'Could not generate summary',
        description: err instanceof Error ? err.message : 'The AI service is temporarily unavailable.',
        variant: 'error',
      })
    } finally {
      setLoading(false)
    }
  }

  return (
    <EditorSection
      title="Professional Summary"
      subtitle={data.summarySource === 'ai' ? 'Generated by AI' : data.summary ? 'Manually written' : 'Empty'}
      icon={<Sparkles className="size-4" />}
      badge={data.summary ? 'Complete' : 'Incomplete'}
    >
      <div className="mb-3 flex items-center justify-between gap-3">
        <Button type="button" variant="outline" size="sm" onClick={() => void generate()} loading={loading}>
          <Sparkles className="size-3.5" />
          {loading ? 'Generating…' : 'Generate Summary'}
        </Button>
        <WritingActions
          text={data.summary}
          role={data.targetJob.role}
          context={resumeTextContext(data)}
          onResult={(t) => patch({ summary: t, summarySource: 'manual' })}
        />
      </div>
      <Textarea
        rows={5}
        value={data.summary}
        onChange={(e) => patch({ summary: e.target.value, summarySource: 'manual' })}
        placeholder="Write a concise summary grounded in your actual experience…"
      />
    </EditorSection>
  )
}

/* ─── Experience ─────────────────────────────────────────────────────── */

export function ExperienceSection() {
  const { data, patch } = useResumeDraft()
  const items = data?.experience ?? []

  const add = () =>
    patch({
      experience: [...items, { id: uid('exp'), company: '', jobTitle: '', location: '', startDate: '', endDate: '', current: false, summary: '', bullets: [], technologies: [] }],
    })
  const remove = (id: string) => patch({ experience: items.filter((e) => e.id !== id) })
  const change = (id: string, p: Partial<ExperienceItem>) =>
    patch({ experience: items.map((e) => (e.id === id ? { ...e, ...p } : e)) })

  return (
    <EditorSection
      title="Work Experience"
      icon={<Briefcase className="size-4" />}
      badge={String(items.length)}
    >
      <Repeatable
        items={items}
        onAdd={add}
        onRemove={remove}
        onChange={(id, p) => change(id, p)}
        addLabel="Add Experience"
        emptyLabel="No experience yet."
        render={(item) => (
          <>
            <div className="grid gap-4 sm:grid-cols-2">
              <TextField label="Job Title" value={item.jobTitle} onChange={(e) => change(item.id, { jobTitle: e.target.value })} />
              <TextField label="Company" value={item.company} onChange={(e) => change(item.id, { company: e.target.value })} />
              <TextField label="Location" optional value={item.location} onChange={(e) => change(item.id, { location: e.target.value })} />
              <div className="flex items-end gap-3 pb-2">
                <Switch
                  checked={item.current}
                  onCheckedChange={(v) => change(item.id, { current: v, endDate: v ? '' : item.endDate })}
                  label="Current role"
                />
                <span className="text-xs text-muted">Current</span>
              </div>
              <MonthField label="Start Date" value={item.startDate ?? ''} onChange={(e) => change(item.id, { startDate: e.target.value })} />
              <MonthField label="End Date" optional disabled={item.current} value={item.current ? '' : (item.endDate ?? '')} onChange={(e) => change(item.id, { endDate: e.target.value })} />
              <div className="sm:col-span-2">
                <TextAreaField label="Role Summary" optional value={item.summary} onChange={(e) => change(item.id, { summary: e.target.value })} />
              </div>
            </div>
            <div>
              <p className="mb-1.5 text-sm font-medium text-muted">Technologies</p>
              <TagsInput value={item.technologies} onChange={(v) => change(item.id, { technologies: v })} placeholder="e.g. React, TypeScript…" ariaLabel="Technologies" />
            </div>
            <div>
              <div className="mb-2 flex items-center justify-between">
                <p className="text-sm font-medium text-muted">Bullets</p>
                <ImproveBulletButton
                  bullet={item.bullets.join(' ')}
                  context={{ jobTitle: item.jobTitle, company: item.company, role: data?.targetJob.role, technologies: item.technologies }}
                  jobDescription={data?.targetJob.jobDescription}
                  label="Improve all with AI"
                  onImproved={(improved) => change(item.id, { bullets: item.bullets.map(() => improved) })}
                />
              </div>
              <BulletsEditorWithAI
                value={item.bullets}
                onChange={(v) => change(item.id, { bullets: v })}
                context={{ jobTitle: item.jobTitle, company: item.company, role: data?.targetJob.role, technologies: item.technologies }}
                jobDescription={data?.targetJob.jobDescription}
              />
            </div>
          </>
        )}
      />
    </EditorSection>
  )
}

