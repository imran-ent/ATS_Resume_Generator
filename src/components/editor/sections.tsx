/* ─── helpers ────────────────────────────────────────────────────────── */

function resumeTextContext(data: NonNullable<ReturnType<typeof useResumeDraft>['data']>) {
  return [
    data.personal.professionalTitle,
    ...data.experience.flatMap((e) => [e.jobTitle, ...e.technologies]),
    ...data.skills.technical.flatMap((g) => g.skills),
  ].filter(Boolean).join(' ')
}