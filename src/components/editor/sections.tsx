/* ─── Skills ─────────────────────────────────────────────────────────── */

export function SkillsSection() {
  const { data, patch } = useResumeDraft()
  if (!data) return null
  const groups = data.skills.technical
  const soft = data.skills.soft

  const setGroups = (next: SkillGroup[]) => patch({ skills: { ...data.skills, technical: next } })
  const setSoft = (next: string[]) => patch({ skills: { ...data.skills, soft: next } })
  const updateGroup = (label: string, skills: string[]) => setGroups(groups.map((g) => (g.label === label ? { ...g, skills } : g)))
  const addGroup = (label: string) => {
    if (groups.some((g) => g.label === label)) return
    setGroups([...groups, { label, skills: [] }])
  }
  const removeGroup = (label: string) => setGroups(groups.filter((g) => g.label !== label))

  return (
    <EditorSection
      title="Skills"
      icon={<Wrench className="size-4" />}
      badge={String(groups.flatMap((g) => g.skills).length)}
    >
      <div className="space-y-3">
        {groups.map((g) => (
          <div key={g.label} className="rounded-md border border-border bg-surface-2/50 p-3">
            <div className="mb-2 flex items-center justify-between">
              <p className="text-xs font-semibold uppercase tracking-wide text-subtle">{g.label}</p>
              <button type="button" onClick={() => removeGroup(g.label)} className="text-xs text-subtle hover:text-danger" aria-label={`Remove ${g.label}`}>
                Remove
              </button>
            </div>
            <TagsInput value={g.skills} onChange={(v) => updateGroup(g.label, v)} placeholder="Type and press Enter…" ariaLabel={`Skills in ${g.label}`} />
          </div>
        ))}
        <div className="flex flex-wrap gap-2">
          {SKILL_CATEGORIES.filter((c) => !groups.some((g) => g.label === c)).map((c) => (
            <button
              key={c}
              type="button"
              onClick={() => addGroup(c)}
              className="focus-ring rounded-md border border-border-strong px-2.5 py-1 text-xs text-muted hover:bg-surface-2 hover:text-foreground"
            >
              + {c}
            </button>
          ))}
        </div>
        <div>
          <p className="mb-1.5 text-sm font-medium text-muted">Soft skills (optional)</p>
          <TagsInput value={soft} onChange={setSoft} placeholder="e.g. Communication…" ariaLabel="Soft skills" />
        </div>
      </div>
    </EditorSection>
  )
}

